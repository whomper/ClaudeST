static int have_dsp, checked, trusted;

static int self_test(void)
{
	unsigned char x[128], e = 3;
	memcpy(x, st_x, sizeof(x));
	return dsp_rsa_public(x, sizeof(x), st_n, sizeof(st_n), &e, 1) && !memcmp(x, st_y, sizeof(x));
}

static int accel(unsigned char *x, size_t xlen, const unsigned char *n, size_t nlen,
		 const unsigned char *e, size_t elen)
{
	unsigned long t0;
	char msg[80];
	int ok;
	if (!checked) {
		checked = 1;
		trusted = self_test();
		conn_log("TLS", " -- ", trusted ? "the DSP passed its self-test" :
			 "the DSP failed its self-test: RSA on the 68030", trusted ? 28 : 46);
	}
	if (!trusted)
		return 0;
	t0 = pf_ms();
	ok = dsp_rsa_public(x, xlen, n, nlen, e, elen);
	snprintf(msg, sizeof(msg), "RSA-%u signature on the %s, %lu ms", (unsigned)(nlen * 8),
		 ok ? "DSP" : "68030 (DSP busy)", pf_ms() - t0);
	conn_log("TLS", " -- ", msg, strlen(msg));
	return ok;
}

void falcon_dsp_init(void)
{
	have_dsp = opt.falcon && opt.dsp && dsp_rsa_present();
	tls_rsa_accel = have_dsp ? accel : 0;
}

const char *falcon_dsp_state(void)
{
	return have_dsp && (!checked || trusted) ? "DSP" : "68030";
}
